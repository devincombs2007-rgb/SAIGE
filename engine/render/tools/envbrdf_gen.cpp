// Generates and verifies the embedded environment BRDF table (src/generated/env_brdf_table.inc).
//
//   saige_envbrdf_gen generate <path>   integrate the table (about 7 s at -O2) and write the include file
//   saige_envbrdf_gen verify            check the embedded table: metadata, checksum, and a spot check recomputed from the code
//
// The table is data, so it can drift from the code that defines the BRDF. `verify` (a CTest test) recomputes 68 texels, the four
// corners and a fixed stride over the grid, with the same integrator and step count, and requires them to match the embedded
// values to within 2 units in the last place of binary16. The tolerance exists because libm trigonometry differs in the last bits
// between toolchains; a changed integrand, clamp or parametrization moves the values by far more than that.
#include "saige/render/env_brdf.hpp"

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

using namespace saige::render;

namespace {

int generate(const char* path)
{
    const EnvBrdfTable table = make_env_brdf_table(kEnvBrdfTableSize, kEnvBrdfTableSteps);
    FILE* f = std::fopen(path, "wb");
    if (f == nullptr) {
        std::fprintf(stderr, "cannot write %s\n", path);
        return 1;
    }
    std::fprintf(f, "// Generated by saige_envbrdf_gen (engine/render/tools/envbrdf_gen.cpp). Do not edit: regenerate with the\n");
    std::fprintf(f, "// saige_regenerate_env_brdf target. Split-sum environment BRDF for the GGX distribution, height-correlated Smith\n");
    std::fprintf(f, "// visibility and Schlick Fresnel weight of pbr.hlsli, roughness clamped to 0.045. Texel (i, j): n.v = (i + 0.5) / size,\n");
    std::fprintf(f, "// perceptual roughness = (j + 0.5) / size; each texel is the binary16 pair (scale, bias).\n");
    std::fprintf(f, "constexpr uint32_t kEnvBrdfTexelsVersion = %u;\n", kEnvBrdfTableVersion);
    std::fprintf(f, "constexpr uint32_t kEnvBrdfTexelsSize = %u;\n", table.size);
    std::fprintf(f, "constexpr int kEnvBrdfTexelsSteps = %d;\n", kEnvBrdfTableSteps);
    std::fprintf(f, "constexpr uint64_t kEnvBrdfTexelsChecksum = 0x%016llxull;\n",
                 static_cast<unsigned long long>(env_brdf_checksum(table.texels.data(), table.texels.size())));
    std::fprintf(f, "constexpr uint16_t kEnvBrdfTexels[] = {");
    for (std::size_t i = 0; i < table.texels.size(); ++i) {
        std::fprintf(f, "%s0x%04x,", i % 12 == 0 ? "\n    " : " ", table.texels[i]);
    }
    std::fprintf(f, "\n};\n");
    std::fclose(f);
    std::printf("wrote %s (%zu values)\n", path, table.texels.size());
    return 0;
}

int fail(const char* what)
{
    std::fprintf(stderr, "env BRDF table check failed: %s\nRegenerate with: cmake --build <dir> --target saige_regenerate_env_brdf "
                         "(and bump kEnvBrdfTableVersion if the BRDF changed)\n", what);
    return 1;
}

int verify()
{
    const EnvBrdfAsset& a = precomputed_env_brdf();
    if (a.version != kEnvBrdfTableVersion) return fail("version differs from kEnvBrdfTableVersion");
    if (a.size != kEnvBrdfTableSize || a.texel_count != std::size_t{kEnvBrdfTableSize} * kEnvBrdfTableSize * 2) return fail("size differs");
    if (a.steps != kEnvBrdfTableSteps) return fail("step count differs");
    if (env_brdf_checksum(a.texels, a.texel_count) != a.checksum) return fail("the texels do not match their recorded checksum");
    // Values must be a sane environment BRDF everywhere: finite, non-negative, scale + bias at most 1 (a white f0 reflects at most
    // what it receives) up to binary16 rounding.
    for (uint32_t j = 0; j < a.size; ++j) {
        for (uint32_t i = 0; i < a.size; ++i) {
            const EnvBrdfValue v = a.at(i, j);
            if (!(v.scale >= 0.0f && v.bias >= 0.0f && v.scale + v.bias <= 1.002f)) return fail("a texel is outside the physical range");
        }
    }
    std::string worst_info;
    int worst = 0;
    const auto check = [&](uint32_t i, uint32_t j) {
        const EnvBrdfValue ref = integrate_env_brdf((static_cast<float>(i) + 0.5f) / static_cast<float>(a.size),
                                                    (static_cast<float>(j) + 0.5f) / static_cast<float>(a.size), a.steps);
        const std::size_t k = (static_cast<std::size_t>(j) * a.size + i) * 2;
        const uint16_t expected[2] = {float_to_half(ref.scale), float_to_half(ref.bias)};
        for (int c = 0; c < 2; ++c) {
            const int d = std::abs(static_cast<int>(a.texels[k + static_cast<std::size_t>(c)]) - static_cast<int>(expected[c]));
            worst = std::max(worst, d);
        }
    };
    const uint32_t last = a.size - 1;
    check(0, 0); check(last, 0); check(0, last); check(last, last);
    for (uint32_t k = 0; k < 64; ++k) {
        check((k * 37u + 5u) % a.size, (k * 11u + 3u) % a.size);
    }
    std::printf("env BRDF table v%u: %ux%u, %d steps, checksum ok, spot-check worst difference %d half ulps\n", a.version, a.size,
                a.size, a.steps, worst);
    return worst <= 2 ? 0 : fail("a recomputed texel differs from the embedded one by more than 2 half ulps");
}

} // namespace

int main(int argc, char** argv)
{
    if (argc == 3 && std::strcmp(argv[1], "generate") == 0) return generate(argv[2]);
    if (argc == 2 && std::strcmp(argv[1], "verify") == 0) return verify();
    std::fprintf(stderr, "usage: saige_envbrdf_gen generate <path> | verify\n");
    return 2;
}
